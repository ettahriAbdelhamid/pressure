#!/bin/bash


#extract parameter from simInput.param
#prepare SimFolder name
#take care of case where multiple sim with same parameters performed 
#create fold structure and copy files for simulation
#print and check simParameters from simInput
#create precMass=ms for Nf=2+1 and different for Nf=3
#prepare rhmc parameter file
#rational approximation inlcuding changing rational Approximation file path in rhmc parameter file
#start sim

mainPath="$(cd "$(dirname "${BASH_SOURCE[0]}")" &> /dev/null && pwd)" 
mainPath="/home/aettahri/simQcd/data"
#rhmc exectuable path
rhmc="${mainPath%/*}/code/buildSIMULATeQCD/applications/rhmc"
rhmcParameterTemplateFile="$mainPath/templates/rhmcParameter.template"
ratApproxExecutable="$mainPath/scripts/ratApprox/ratApproxNoisy"
#these two files are generated by ratApproxNoisy and will be deleted afterwards. there are only needed for checking what ratApprox degree to use.
#Since we dont need this calculation anymore they are for us useless (for now)
errorMDFile="errorMD.dat"
errorFAFile="errorFA.dat"
##########################
#extract parameters#######
##########################
#simInput file contains all parameters needed for simulation. Also used to generate rhmcParameter file.
if [ -f "$1" ]; then simInput=$(realpath "$1")
else echo "Error: Input file '$1' not found."; exit 1;
fi

#extract parameters as associative array, while also removing white spaces and comments from values 
declare -A params
while IFS='=' read -r key value || [[ -n "$key" ]]; do
    [[ -z "$key" || "$key" =~ ^# ]] && continue #skip comments and empty lines
    value="${value%%#*}"           
    value="${value//[[:space:]]/}" #remove comments and whitespaces #second would fail if value contains spaces, which should never happen. 
    key="${key//[[:space:]]/}"     #remove whitespaces from key
    params["$key"]="$value"
done < "$simInput"

ml=${params[massL]}
ms=${params[massS]}
ns=${params[latS]}
nt=${params[latT]}
beta=${params[beta]}
md=${params[numStepTraj]}
stepSf=${params[numStepStrangeInt]}
sw=${params[numStepGaugeInt]}
simMainFolderName=${params[simFolderName]}  #somthing like "simOptimization", "free_theory", "test", or just "sim" or something else

##########################
#prepare simFolder name###
##########################
#if these parameters are not set, the folders cannot be prepared
for var in $ml $ms $ns $nt $beta; do
    if [ -z $var ]; then 
        echo "Error: {massS, massL, beta, latS, latT} must be set in input file."
        exit 1 
    fi
done
simFolder="$mainPath/simulations/$simMainFolderName"
simFolder="$simFolder/ns_${params[latS]}_nt_${params[latT]}/beta_${params[beta]}_ml_${params[massL]}_ms_${params[massS]}"
#special foldername for optimization runs
if [ "$simMainFolderName" = "simOptimization" ] || [ "$simMainFolderName" = "simOptimizationThermalized" ]; then simFolder="${simFolder}_opti_${md}_${stepSf}_${sw}"; fi

################################################################
#what if folder already done with these parameters:#############
################################################################
#simulations that share these 5 parameters are placed in the same folder, and numbered consecutively. 
dirs=$(ls -d "$simFolder"/std* 2>/dev/null)                                  #find all directories starting with std
if [ -z "$dirs" ]; then                                         #if none exist, create std folder
    simFolder="$simFolder/std" 
else 
    n=$(echo "$dirs" | grep -o '[0-9]*$' | sort -n | tail -1)   #otherwise find highest number after std and increment by 1
    simFolder="$simFolder"/"std$((${n:-1} + 1))"
fi


#################
#create Folders##
#################
#create folders and logFile. Copy inputFile and the template version of the rhmcParameter file to the parameter folder. 
mkdir -p "$simFolder"
docFolder="$simFolder/doc"
mkdir $docFolder
mkdir "$simFolder/analysis"
logFile="$docFolder/log.log"
#cp "$simInput" "$docFolder"
rhmcParameterFile="$docFolder/rhmc.param"
cp $rhmcParameterTemplateFile "$rhmcParameterFile"

#Shortcut for logging to logFile. Usage: log "message"
log() {
    printf "[$(date "+%Y-%m-%d %H:%M:%S")] $1\n" | tee -a "$logFile"
}
logNoTime() {
    printf "$1\n" | tee -a "$logFile"
}

log "Starting RHMC Simulation\n***************"
log "Folder Struture generated. Simulation will be placed in $simFolder"



#################################################################
#check that everything all parameters are set and print in log###
#################################################################
log "Parameters read from input file:"

keys=("latS" "latT" "massL" "massS" "beta")                                                             #Essential for folder structure
keys+=("nodeX" "nodeY" "nodeZ" "nodeT")
keys+=("stepSize" "numStepTraj" "numStepStrangeInt" "numStepGaugeInt" "maxCG")                          #RHMC update parameters (I think)                  
keys+=("newRand" "randPath" "startRandPath" "seed" "loadConf" "gaugePath" "startGaugePath" "confNum" "numUpdate" "writeEvery")   #More RHMC update parameters (I think)
keys+=("simFolderName" "noSkipMetro")                                                                                       

for key in "${keys[@]}"; do
    if [ -z "${params[$key]}" ]; then logNoTime "Warning: '$key' not set in input file."
    else                              logNoTime "$key = ${params[$key]}"
    fi
done


################
#for Nf=3#######
################
get_precond_mass() {
    mass=$1
    awk -v m="$mass" 'BEGIN{printf "%.6f\n", sqrt(5 / (sqrt((5+m*m) / (m*m)) - 1))}'
}
if awk -v ml="$ml" -v ms="$ms" 'BEGIN { exit ((ml + 0) == (ms + 0) ? 0 : 1) }'; then
    precMass=$(get_precond_mass $ms)
else
    precMass=$ms
fi

##################################################################################################################
#Prepare rhmc parameter file. Only degMD and degFA are done below and necessary for rational approximation file:##
##################################################################################################################
log "Generating rhmcParameter file from template using previously read parameters. Unset parameters are set by default."
#cannot use s//g for files since they contain slashes. so use | as delimiter
if ! sed -i -E "
  s/latticeSpace/${params[latS]}/g;
  s/latticeTemp/${params[latT]}/g;
  s/massLight/${params[massL]}/g;
  s/massStrange/${params[massS]}/g;
  s/nodeXVal/${params[nodeX]:-1}/g;
  s/nodeYVal/${params[nodeY]:-1}/g;
  s/nodeZVal/${params[nodeZ]:-1}/g;
  s/nodeTVal/${params[nodeT]:-1}/g;
  s/precMass/${precMass}/g;
  s/betaVal/${params[beta]}/g;
  s/betaPlaqVal/${params[betaPlaq]:-1}/g;
  s/betaRectVal/${params[betaRect]:-1}/g;
  s/stepSizeVal/${params[stepSize]:-1}/g;
  s/numStepsOfTrajectory/${params[numStepTraj]:-1}/g;
  s/numStepsStrangeInt/${params[numStepStrangeInt]:-1}/g;
  s/numStepsGaugeInt/${params[numStepGaugeInt]:-1}/g;
  s/maxCGSteps/${params[maxCG]:-20000}/g;
  s/randFileBool/${params[newRand]:-0}/g;
  s|randFile|${params[randPath]:-0}|g;
  s|startRandFile|${params[startRandPath]:-0}|g;
  s/seedVal/${params[seed]:-0}/g;
  s/loadConfBool/${params[loadConf]:-0}/g;
  s|gaugeFieldFile|${params[gaugePath]:-0}|g;
  s|startGaugeFile|${params[startGaugePath]:-0}|g;
  s/confNum/${params[confNum]:-987654321}/g;
  s/numUpdates/${params[numUpdate]:-1}/g;
  s/writeEvery/${params[writeEvery]:-1}/g;
  s/noSkipMetroVal/${params[noSkipMetro]:-1}/g
" "$rhmcParameterFile"  2>>"$logFile"; then
    log "Error: sed substitution failed, check log above."
    exit 1
fi
log "rhmcParameter file generated at $rhmcParameterFile"
log "*****************************************************************"

###################################
##Rational Approximation stuff:####
###################################
#############################################################################
#only relevant if i calculate rational approximation for different degrees###
#############################################################################
#masses3FileWithDegree="$mainPath/scripts/ratApprox/masses3_with_degree.param"
#masses2p1FileWithDegree="$mainPath/scripts/ratApprox/masses2p1_with_degree.param"
##wait!!!!!BC would fail on cluster      if (( $(echo "${params[massL]} == ${params[massS]}" | bc -l) )); then
#    massesFileWithDegree=$masses3FileWithDegree    
#else
#    massesFileWithDegree=$masses2p1FileWithDegree
#fi

#read -r degFA degMD < <(awk -v ml="${params[massL]}" -v ms="${params[massS]}" '$1 == ml && $2 == ms {print $3, $4}' $massesFileWithDegree)


degFA=14; degMD=12; precision=160; eigenvalueLength=5
ratApproxParameterFile="$mainPath/parameter/ratApprox/ml_${params[massL]}_ms_${params[massS]}_degFA_${degFA}_degMD_${degMD}.rat"

log "Rational Approximation with degree ${degFA} for FA and degre ${degMD} for MD"
sed -i -E "s/degFAval/${degFA}/g;s/degMDval/${degMD}/g" "$rhmcParameterFile" 2>>"$logFile"; 


if [ ! -f "$ratApproxParameterFile" ] ; then
    log "Rational Approximation not found. Generating new file in $ratApproxParameterFile."
    SECONDS=0    
    tmpRatApproxInput="$simFolder/ratApproxInput.param"
    bash "$mainPath/scripts/ratApprox/generateRatApproxFile.sh" "$ml" "$ms" "$degFA" "$degMD" "$precision" "$eigenvalueLength" > $tmpRatApproxInput
    $ratApproxExecutable $tmpRatApproxInput > $ratApproxParameterFile
    rm $tmpRatApproxInput
    #dont need these two error files. just a by product of ratApproxNoisy
    rm $errorFAFile
    rm $errorMDFile

    if [ ! -f "$ratApproxParameterFile" ]; then log "Error: rational approx generation failed"; exit 1; fi
    log "Generation completed in $SECONDS seconds."
else
    log "Rational approximation already exists for given masses."    
fi


#log "Copy Rational Approximation Parameter file into $docFolder."
#cp $ratApproxParameterFile $docFolder

if [ "$(wc -l < "$ratApproxParameterFile")" -lt 50 ]; then 
    log "WARNING: has less than 50 lines, might be incomplete";  
fi


#################
#Starting Sim:###
#################

log "****************************************************************"
log "Preparation completed. Starting rhmc simulation."
log "****************************************************************"

#will propbably always be 1
world_size=$((${params["nodeX"]} * ${params["nodeY"]} *${params["nodeZ"]} *${params["nodeT"]}))

# stdbuf to print instantly stdout (-oL) and stderr (-eL).
# 2>&1 to combine both to stdout. 
# tee to print to stdout and logFile.

stdbuf -oL -eL "$rhmc" "$rhmcParameterFile" 2>&1 | stdbuf -oL tee -a "$logFile" 
#stdbuf -oL -eL srun --exclusive --ntasks 2 "$rhmc" "$rhmcParameterFile" 2>&1 | stdbuf -oL tee -a "$logFile" 
#apparently i should wrap everything in bash -c so that not only the first part is in nohup?
#bash -c "stdbuf -oL -eL mpirun -np ${world_size} '$rhmc' '$rhmcParameterFile' 2>&1 | stdbuf -oL tee -a '$logFile'"
